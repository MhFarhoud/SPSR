export function followUpScaleLevel(domain: string, score: number): "بهنجار" | "مرزی" | "نابهنجار" {
  switch (domain) {
    case "نشانگان هیجانی": return score <= 4 ? "بهنجار" : score === 5 ? "مرزی" : "نابهنجار";
    case "مشکلات سلوک": return score <= 2 ? "بهنجار" : score === 3 ? "مرزی" : "نابهنجار";
    case "بیش‌فعالی و کمبود توجه": return score <= 5 ? "بهنجار" : score === 6 ? "مرزی" : "نابهنجار";
    case "مشکلات با همتایان": return score <= 3 ? "بهنجار" : score === 4 ? "مرزی" : "نابهنجار";
    case "رفتارهای جامعه‌پسند": return score >= 6 ? "بهنجار" : score === 5 ? "مرزی" : "نابهنجار";
    default: return "بهنجار";
  }
}

export function scoreFollowUpScale(answers: AssessmentAnswer[], domain: string): number {
  const scale = FOLLOW_UP_SCALES.find(item => item.domain === domain);
  if (!scale) throw new Error(`Unknown follow-up domain: ${domain}`);
  const reverseItems = new Set([7, 11, 14, 21, 25]);
  return scale.questions.reduce((total, questionId) => {
    const value = answers.find(answer => Number(answer.questionId) === questionId)?.answerValue;
    if (typeof value !== "number") return total;
    const itemScore = value === 1 ? 1 : value === 2 ? (reverseItems.has(questionId) ? 0 : 2) : reverseItems.has(questionId) ? 2 : 0;
    return total + itemScore;
  }, 0);
}
